-- =============================================================================
-- 4. TEMPORADAS (2024-01-01 a 2027-01-15, contiguas y sin solapamiento)
--    Por anio: fin de anio (ALTA), baja, Semana Santa (ALTA), baja,
--    vacaciones de mitad de anio (ALTA), baja, receso de octubre (MEDIA),
--    baja, pretemporada navidena (MEDIA), temporada navidena (ALTA).
-- =============================================================================
DECLARE
    v_id     PLS_INTEGER := 0;
    v_ss_ini DATE;
    v_ss_fin DATE;

    FUNCTION f(p_anio PLS_INTEGER, p_mmdd VARCHAR2) RETURN DATE IS
    BEGIN
        RETURN TO_DATE(p_anio || '-' || p_mmdd, 'YYYY-MM-DD');
    END;

    PROCEDURE agregar(p_nombre VARCHAR2, p_ini DATE, p_fin DATE, p_tipo VARCHAR2) IS
    BEGIN
        v_id := v_id + 1;
        INSERT INTO temporada (id_temporada, nombre, fecha_inicio, fecha_fin, tipo_temporada)
        VALUES (v_id, p_nombre, p_ini, p_fin, p_tipo);
    END;
BEGIN
    FOR y IN 2024 .. 2026 LOOP
        -- Domingo de Ramos a Domingo de Resurreccion de cada anio
        v_ss_ini := CASE y
                        WHEN 2024 THEN DATE '2024-03-24'
                        WHEN 2025 THEN DATE '2025-04-13'
                        ELSE DATE '2026-03-29'
                    END;
        v_ss_fin := v_ss_ini + 7;

        agregar('Temporada de fin de anio ' || (y - 1) || '-' || y,
                f(y, '01-01'), f(y, '01-15'), 'ALTA');
        agregar('Temporada baja primer trimestre ' || y,
                f(y, '01-16'), v_ss_ini - 1, 'BAJA');
        agregar('Semana Santa ' || y,
                v_ss_ini, v_ss_fin, 'ALTA');
        agregar('Temporada baja abril-junio ' || y,
                v_ss_fin + 1, f(y, '06-14'), 'BAJA');
        agregar('Vacaciones de mitad de anio ' || y,
                f(y, '06-15'), f(y, '07-20'), 'ALTA');
        agregar('Temporada baja julio-septiembre ' || y,
                f(y, '07-21'), f(y, '09-30'), 'BAJA');
        agregar('Receso escolar de octubre ' || y,
                f(y, '10-01'), f(y, '10-15'), 'MEDIA');
        agregar('Temporada baja octubre-noviembre ' || y,
                f(y, '10-16'), f(y, '11-15'), 'BAJA');
        agregar('Pretemporada navidena ' || y,
                f(y, '11-16'), f(y, '12-14'), 'MEDIA');
        agregar('Temporada navidena ' || y,
                f(y, '12-15'), f(y, '12-31'), 'ALTA');
    END LOOP;

    -- Cubre las noches de enero 2027 de las reservas que entran en diciembre 2026.
    agregar('Temporada de fin de anio 2026-2027',
            DATE '2027-01-01', DATE '2027-01-15', 'ALTA');

    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Temporadas: ' || v_id);
END;
/

-- =============================================================================
-- 5. TARIFAS: una por habitacion y temporada (400 x 31 = 12.400)
--    precio = base del tipo de habitacion
--             x factor del tipo de alojamiento
--             x variacion propia de la habitacion (+-10 %)
--             x factor de temporada (ALTA 1.35, MEDIA 1.15, BAJA 1.00)
--             x ajuste anual (2024 1.00, 2025 1.06, 2026 1.12)
--    redondeado a miles de pesos.
-- =============================================================================
DECLARE
    v_base        NUMBER;
    v_factor_tipo NUMBER;
    v_factor_temp NUMBER;
    v_factor_anio NUMBER;
    v_precio      NUMBER;
    v_total       PLS_INTEGER := 0;
BEGIN
    FOR h IN (
        SELECT h.id_habitacion, h.id_tipo_habitacion, a.id_tipo_alojamiento
        FROM   habitacion h
        JOIN   alojamiento a ON a.id_alojamiento = h.id_alojamiento
        ORDER BY h.id_habitacion
    ) LOOP
        v_base := CASE h.id_tipo_habitacion
                      WHEN 1 THEN 110000
                      WHEN 2 THEN 170000
                      WHEN 3 THEN 230000
                      WHEN 4 THEN 320000
                      WHEN 5 THEN 360000
                      ELSE 65000
                  END;
        v_factor_tipo := CASE h.id_tipo_alojamiento
                             WHEN 1 THEN 1.10   -- Finca cafetera
                             WHEN 2 THEN 1.00   -- Hotel
                             WHEN 3 THEN 1.35   -- Glamping
                             WHEN 4 THEN 0.60   -- Hostal
                             WHEN 5 THEN 0.90   -- Cabana
                             ELSE 1.40          -- Hotel boutique
                         END;
        v_base := v_base * v_factor_tipo * DBMS_RANDOM.VALUE(0.9, 1.1);

        FOR t IN (
            SELECT id_temporada, tipo_temporada,
                   EXTRACT(YEAR FROM fecha_inicio) AS anio
            FROM   temporada
            ORDER BY id_temporada
        ) LOOP
            v_factor_temp := CASE t.tipo_temporada
                                 WHEN 'ALTA'  THEN 1.35
                                 WHEN 'MEDIA' THEN 1.15
                                 ELSE 1.00
                             END;
            v_factor_anio := CASE
                                 WHEN t.anio <= 2024 THEN 1.00
                                 WHEN t.anio = 2025  THEN 1.06
                                 ELSE 1.12
                             END;
            v_precio := ROUND(v_base * v_factor_temp * v_factor_anio, -3);

            INSERT INTO tarifa (id_habitacion, id_temporada, precio_noche)
            VALUES (h.id_habitacion, t.id_temporada, v_precio);
            v_total := v_total + 1;
        END LOOP;
    END LOOP;

    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Tarifas: ' || v_total);
END;
/

-- =============================================================================
-- 6. RESERVAS, HABITACIONES RESERVADAS Y SERVICIOS
--    Se generan 25.000 reservas con check-in entre 2024-01-01 y 2026-12-31.
--    Todo el control de disponibilidad se hace en memoria (colecciones
--    indexadas) para garantizar que no haya solapamientos por habitacion.
-- =============================================================================
DECLARE
    c_total_reservas   CONSTANT PLS_INTEGER := 25000;
    c_min_lineas_serv  CONSTANT PLS_INTEGER := 40000;
    c_fecha_base       CONSTANT DATE        := DATE '2024-01-01';
    c_ultimo_dia       CONSTANT PLS_INTEGER := DATE '2026-12-31' - DATE '2024-01-01';
    c_dias_por_hab     CONSTANT PLS_INTEGER := 1200;
    c_max_intentos     CONSTANT PLS_INTEGER := 3000000;

    TYPE t_num  IS TABLE OF NUMBER       INDEX BY PLS_INTEGER;
    TYPE t_txt  IS TABLE OF VARCHAR2(10) INDEX BY PLS_INTEGER;
    TYPE t_bool IS TABLE OF BOOLEAN      INDEX BY PLS_INTEGER;

    -- Calendario: temporada de cada dia (indice = dias desde 2024-01-01)
    v_dia_temp          t_num;
    v_dia_tipo          t_txt;
    -- Tarifas: indice = id_habitacion * 100 + id_temporada
    v_tarifa            t_num;
    -- Habitaciones
    v_hab_cap           t_num;
    v_hab_ok            t_bool;
    -- Alojamientos
    v_aloj_primera_hab  t_num;
    v_aloj_num_hab      t_num;
    v_aloj_primer_serv  t_num;
    v_aloj_num_serv     t_num;
    v_aloj_pop          t_num;
    -- Servicios
    v_serv_precio       t_num;
    -- Ocupacion: indice = (id_habitacion - 1) * 1200 + dia
    v_ocupado           t_bool;
    -- Reservas generadas
    v_res_aloj          t_num;
    v_res_cancelada     t_bool;
    -- Habitaciones elegidas para la reserva en curso
    v_elegidas          t_num;

    v_ahora         DATE := CAST(
        TO_TIMESTAMP_TZ(:carga_referencia, 'FXYYYY-MM-DD HH24:MI:SS TZR')
        AT TIME ZONE 'America/Bogota' AS DATE);
    v_hoy           DATE := TRUNC(v_ahora);
    v_id_res        PLS_INTEGER := 0;
    v_intentos      PLS_INTEGER := 0;
    v_lineas_serv   PLS_INTEGER := 0;
    v_lineas_hab    PLS_INTEGER := 0;
    v_aloj          PLS_INTEGER;
    v_dia           PLS_INTEGER;
    v_noches        PLS_INTEGER;
    v_hab_req       PLS_INTEGER;
    v_inicio        PLS_INTEGER;
    v_hab           PLS_INTEGER;
    v_encontradas   PLS_INTEGER;
    v_cliente       PLS_INTEGER;
    v_personas      PLS_INTEGER;
    v_n_serv        PLS_INTEGER;
    v_ini_serv      PLS_INTEGER;
    v_serv          PLS_INTEGER;
    v_cant          PLS_INTEGER;
    v_id            PLS_INTEGER;
    v_libre         BOOLEAN;
    v_checkin       DATE;
    v_checkout      DATE;
    v_fecha_res     DATE;
    v_estado        VARCHAR2(12);
    v_r             NUMBER;
    v_prob          NUMBER;
    v_precio        NUMBER;
    v_anticipacion  NUMBER;
    v_inicio_tramo  PLS_INTEGER;
    v_fin_tramo     PLS_INTEGER;
    v_lineas_tramo  PLS_INTEGER := 0;
BEGIN
    -- ---------------------------------------------------------------------
    -- Cargar a memoria lo que se necesita
    -- ---------------------------------------------------------------------
    FOR t IN (SELECT id_temporada, fecha_inicio, fecha_fin, tipo_temporada
              FROM temporada ORDER BY id_temporada) LOOP
        FOR d IN (t.fecha_inicio - c_fecha_base) .. (t.fecha_fin - c_fecha_base) LOOP
            IF d >= 0 THEN
                v_dia_temp(d) := t.id_temporada;
                v_dia_tipo(d) := t.tipo_temporada;
            END IF;
        END LOOP;
    END LOOP;

    FOR t IN (SELECT id_habitacion, id_temporada, precio_noche FROM tarifa
              ORDER BY id_habitacion, id_temporada) LOOP
        v_tarifa(t.id_habitacion * 100 + t.id_temporada) := t.precio_noche;
    END LOOP;

    FOR h IN (SELECT h.id_habitacion, h.estado, th.capacidad_estandar
              FROM   habitacion h
              JOIN   tipo_habitacion th
                     ON th.id_tipo_habitacion = h.id_tipo_habitacion
              ORDER BY h.id_habitacion) LOOP
        v_hab_cap(h.id_habitacion) := h.capacidad_estandar;
        v_hab_ok(h.id_habitacion)  := (h.estado = 'DISPONIBLE');
    END LOOP;

    FOR a IN (SELECT id_alojamiento, MIN(id_habitacion) AS primera, COUNT(*) AS num
              FROM habitacion GROUP BY id_alojamiento ORDER BY id_alojamiento) LOOP
        v_aloj_primera_hab(a.id_alojamiento) := a.primera;
        v_aloj_num_hab(a.id_alojamiento)     := a.num;
    END LOOP;

    FOR a IN (SELECT id_alojamiento, MIN(id_servicio) AS primero, COUNT(*) AS num
              FROM servicio GROUP BY id_alojamiento ORDER BY id_alojamiento) LOOP
        v_aloj_primer_serv(a.id_alojamiento) := a.primero;
        v_aloj_num_serv(a.id_alojamiento)    := a.num;
    END LOOP;

    FOR s IN (SELECT id_servicio, precio_unitario FROM servicio ORDER BY id_servicio) LOOP
        v_serv_precio(s.id_servicio) := s.precio_unitario;
    END LOOP;

    -- Popularidad: los municipios mas turisticos reciben mas reservas.
    FOR a IN (SELECT id_alojamiento, id_municipio FROM alojamiento
              ORDER BY id_alojamiento) LOOP
        v_aloj_pop(a.id_alojamiento) :=
            DBMS_RANDOM.VALUE(0.35, 0.8)
            + CASE WHEN a.id_municipio IN (1, 6, 9, 11, 12) THEN 0.2 ELSE 0 END;
    END LOOP;

    -- ---------------------------------------------------------------------
    -- Generacion de reservas
    -- ---------------------------------------------------------------------
    WHILE v_id_res < c_total_reservas LOOP
        v_intentos := v_intentos + 1;
        IF v_intentos > c_max_intentos THEN
            RAISE_APPLICATION_ERROR(-20001,
                'No fue posible generar todas las reservas. Generadas: ' || v_id_res);
        END IF;

        v_dia  := TRUNC(DBMS_RANDOM.VALUE(0, c_ultimo_dia + 1));
        v_aloj := TRUNC(DBMS_RANDOM.VALUE(1, 61));

        -- Aceptacion segun temporada y popularidad del alojamiento
        v_prob := CASE v_dia_tipo(v_dia)
                      WHEN 'ALTA'  THEN 1.00
                      WHEN 'MEDIA' THEN 0.55
                      ELSE 0.30
                  END * v_aloj_pop(v_aloj);

        IF DBMS_RANDOM.VALUE < v_prob THEN
            -- Noches de estadia (1 a 7, mayoria entre 2 y 3)
            v_r := DBMS_RANDOM.VALUE;
            v_noches := CASE
                            WHEN v_r < 0.15 THEN 1
                            WHEN v_r < 0.45 THEN 2
                            WHEN v_r < 0.70 THEN 3
                            WHEN v_r < 0.85 THEN 4
                            WHEN v_r < 0.93 THEN 5
                            WHEN v_r < 0.97 THEN 6
                            ELSE 7
                        END;

            -- Habitaciones pedidas (80 % una sola)
            v_r := DBMS_RANDOM.VALUE;
            v_hab_req := CASE WHEN v_r < 0.80 THEN 1
                              WHEN v_r < 0.95 THEN 2
                              ELSE 3 END;

            -- Buscar habitaciones libres en todas las noches de la estadia
            v_elegidas.DELETE;
            v_encontradas := 0;
            v_inicio := TRUNC(DBMS_RANDOM.VALUE(0, v_aloj_num_hab(v_aloj)));

            FOR j IN 0 .. v_aloj_num_hab(v_aloj) - 1 LOOP
                EXIT WHEN v_encontradas = v_hab_req;
                v_hab := v_aloj_primera_hab(v_aloj) + MOD(v_inicio + j, v_aloj_num_hab(v_aloj));

                IF v_hab_ok(v_hab) THEN
                    v_libre := TRUE;
                    FOR d IN v_dia .. v_dia + v_noches - 1 LOOP
                        IF v_ocupado.EXISTS((v_hab - 1) * c_dias_por_hab + d) THEN
                            v_libre := FALSE;
                            EXIT;
                        END IF;
                    END LOOP;

                    IF v_libre THEN
                        v_encontradas := v_encontradas + 1;
                        v_elegidas(v_encontradas) := v_hab;
                    END IF;
                END IF;
            END LOOP;

            IF v_encontradas > 0 THEN
                v_id_res   := v_id_res + 1;
                v_checkin  := c_fecha_base + v_dia;
                v_checkout := v_checkin + v_noches;
                v_cliente  := TRUNC(DBMS_RANDOM.VALUE(101, 3101));

                -- Estado segun la fecha de referencia de esta corrida
                v_r := DBMS_RANDOM.VALUE;
                IF v_checkout <= v_hoy THEN
                    v_estado := CASE WHEN v_r < 0.90 THEN 'FINALIZADA' ELSE 'CANCELADA' END;
                ELSIF v_checkin <= v_hoy THEN
                    v_estado := 'CHECKED_IN';
                ELSE
                    v_estado := CASE WHEN v_r < 0.70 THEN 'CONFIRMADA'
                                     WHEN v_r < 0.90 THEN 'PENDIENTE'
                                     ELSE 'CANCELADA' END;
                END IF;

                -- Anticipacion de la reserva: mayor en temporada alta
                v_anticipacion := CASE v_dia_tipo(v_dia)
                                      WHEN 'ALTA'  THEN DBMS_RANDOM.VALUE(15, 75)
                                      WHEN 'MEDIA' THEN DBMS_RANDOM.VALUE(7, 45)
                                      ELSE DBMS_RANDOM.VALUE(0.5, 25)
                                  END;
                v_fecha_res := v_checkin - v_anticipacion;
                IF v_fecha_res > v_ahora THEN
                    v_fecha_res := v_ahora - DBMS_RANDOM.VALUE(1, 30);
                END IF;

                INSERT INTO reserva (
                    id_reserva, id_cliente, id_alojamiento, fecha_reserva,
                    fecha_checkin, fecha_checkout, estado, valor_total
                ) VALUES (
                    v_id_res, v_cliente, v_aloj, CAST(v_fecha_res AS TIMESTAMP),
                    v_checkin, v_checkout, v_estado, 0
                );

                -- Habitaciones de la reserva: precio noche a noche
                FOR e IN 1 .. v_encontradas LOOP
                    v_hab := v_elegidas(e);
                    v_precio := 0;
                    FOR d IN v_dia .. v_dia + v_noches - 1 LOOP
                        v_precio := v_precio + v_tarifa(v_hab * 100 + v_dia_temp(d));
                        v_ocupado((v_hab - 1) * c_dias_por_hab + d) := TRUE;
                    END LOOP;

                    v_personas := TRUNC(DBMS_RANDOM.VALUE(1, v_hab_cap(v_hab) + 1));

                    INSERT INTO reserva_habitacion (
                        id_reserva, id_habitacion, personas_hospedadas,
                        precio_estadia_habitacion
                    ) VALUES (
                        v_id_res, v_hab, v_personas, v_precio
                    );
                    v_lineas_hab := v_lineas_hab + 1;

                    -- Primero existe el detalle padre; despues se captura cada
                    -- tramo de temporada. El fin del tramo es EXCLUSIVO.
                    v_inicio_tramo := v_dia;
                    WHILE v_inicio_tramo < v_dia + v_noches LOOP
                        v_fin_tramo := v_inicio_tramo + 1;
                        WHILE v_fin_tramo < v_dia + v_noches
                              AND v_dia_temp(v_fin_tramo) = v_dia_temp(v_inicio_tramo) LOOP
                            v_fin_tramo := v_fin_tramo + 1;
                        END LOOP;

                        INSERT INTO reserva_habitacion_tarifa_aplicada (
                            id_reserva, id_habitacion, fecha_inicio_tramo,
                            fecha_fin_tramo, id_temporada, tipo_temporada_aplicado,
                            precio_noche_aplicado, origen_dato, referencia_evidencia
                        ) VALUES (
                            v_id_res, v_hab, c_fecha_base + v_inicio_tramo,
                            c_fecha_base + v_fin_tramo, v_dia_temp(v_inicio_tramo),
                            v_dia_tipo(v_inicio_tramo),
                            v_tarifa(v_hab * 100 + v_dia_temp(v_inicio_tramo)),
                            'CAPTURADO', NULL
                        );
                        v_lineas_tramo := v_lineas_tramo + 1;
                        v_inicio_tramo := v_fin_tramo;
                    END LOOP;
                END LOOP;

                v_res_aloj(v_id_res)      := v_aloj;
                v_res_cancelada(v_id_res) := (v_estado = 'CANCELADA');

                -- Servicios (solo reservas no canceladas): 0 a 4 distintos
                IF v_estado <> 'CANCELADA' THEN
                    v_r := DBMS_RANDOM.VALUE;
                    v_n_serv := CASE
                                    WHEN v_r < 0.12 THEN 0
                                    WHEN v_r < 0.40 THEN 1
                                    WHEN v_r < 0.70 THEN 2
                                    WHEN v_r < 0.88 THEN 3
                                    ELSE 4
                                END;
                    v_n_serv   := LEAST(v_n_serv, v_aloj_num_serv(v_aloj));
                    v_ini_serv := TRUNC(DBMS_RANDOM.VALUE(0, v_aloj_num_serv(v_aloj)));

                    FOR s IN 0 .. v_n_serv - 1 LOOP
                        v_serv := v_aloj_primer_serv(v_aloj)
                                  + MOD(v_ini_serv + s, v_aloj_num_serv(v_aloj));
                        v_cant   := TRUNC(DBMS_RANDOM.VALUE(1, 5));
                        v_precio := v_serv_precio(v_serv);

                        INSERT INTO reserva_servicio (
                            id_reserva, id_servicio, cantidad,
                            precio_unitario_aplicado, subtotal
                        ) VALUES (
                            v_id_res, v_serv, v_cant, v_precio,
                            ROUND(v_cant * v_precio, 2)
                        );
                        v_lineas_serv := v_lineas_serv + 1;
                    END LOOP;
                END IF;

                IF MOD(v_id_res, 5000) = 0 THEN
                    DBMS_OUTPUT.PUT_LINE('Reservas generadas: ' || v_id_res);
                END IF;
            END IF;
        END IF;
    END LOOP;

    -- ---------------------------------------------------------------------
    -- Completar hasta el minimo de 40.000 lineas de servicio si hiciera falta
    -- ---------------------------------------------------------------------
    -- Recorrido acotado de todas las combinaciones elegibles. Si la capacidad
    -- fuese insuficiente se falla expresamente, sin un bucle aleatorio infinito.
    FOR reserva_pendiente IN 1 .. v_id_res LOOP
        EXIT WHEN v_lineas_serv >= c_min_lineas_serv;
        v_id := reserva_pendiente;
        IF NOT v_res_cancelada(v_id) THEN
            v_aloj   := v_res_aloj(v_id);
            FOR servicio_pendiente IN 0 .. v_aloj_num_serv(v_aloj) - 1 LOOP
                EXIT WHEN v_lineas_serv >= c_min_lineas_serv;
                v_serv   := v_aloj_primer_serv(v_aloj) + servicio_pendiente;
                v_cant   := TRUNC(DBMS_RANDOM.VALUE(1, 5));
                v_precio := v_serv_precio(v_serv);
                BEGIN
                    INSERT INTO reserva_servicio (
                        id_reserva, id_servicio, cantidad,
                        precio_unitario_aplicado, subtotal
                    ) VALUES (
                        v_id, v_serv, v_cant, v_precio, ROUND(v_cant * v_precio, 2)
                    );
                    v_lineas_serv := v_lineas_serv + 1;
                EXCEPTION
                    WHEN DUP_VAL_ON_INDEX THEN NULL;
                END;
            END LOOP;
        END IF;
    END LOOP;
    IF v_lineas_serv < c_min_lineas_serv THEN
        RAISE_APPLICATION_ERROR(-20013,
            'Capacidad insuficiente para completar las 40.000 lineas de servicio.');
    END IF;

    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Reservas: ' || v_id_res
                         || ' | habitaciones reservadas: ' || v_lineas_hab
                         || ' | tramos capturados: ' || v_lineas_tramo
                         || ' | lineas de servicio: ' || v_lineas_serv
                         || ' | intentos: ' || v_intentos);
END;

-- =============================================================================
-- 3. OFERTA: 60 alojamientos, 400 habitaciones, comodidades y servicios
--    5 alojamientos por municipio, 10 de cada tipo.
--    Habitaciones: los primeros 40 alojamientos tienen 7 y los ultimos 20
--    tienen 6  ->  40*7 + 20*6 = 400.
-- =============================================================================
DECLARE
    TYPE t_txt IS TABLE OF VARCHAR2(60);
    TYPE t_num IS TABLE OF NUMBER;

    v_prefijos t_txt := t_txt(
        'Finca', 'Hotel', 'Glamping', 'Hostal', 'Cabanas', 'Hotel Boutique');
    v_palabras t_txt := t_txt(
        'El Cafetal', 'La Palma de Cera', 'Los Guaduales', 'El Mirador',
        'Las Heliconias', 'La Esperanza', 'El Arriero', 'Bosque de Niebla',
        'Brisas del Quindio', 'La Montana', 'El Yarumo', 'Villa Cafe',
        'Los Balcones', 'La Cascada', 'El Bambu', 'Rio Verde', 'La Colina',
        'El Barranquero', 'Tierra Paisa', 'Monte Azul');
    v_serv_nombres t_txt := t_txt(
        'Desayuno tipico', 'Tour del cafe', 'Cabalgata',
        'Transporte aeropuerto', 'Masaje relajante', 'Parqueadero cubierto',
        'Lavanderia', 'Cena romantica');
    v_serv_precios t_num := t_num(
        25000, 60000, 80000, 90000, 120000, 15000, 20000, 150000);

    v_id_aloj    PLS_INTEGER := 0;
    v_id_hab     PLS_INTEGER := 0;
    v_id_serv    PLS_INTEGER := 0;
    v_tipo       PLS_INTEGER;
    v_tipo_hab   PLS_INTEGER;
    v_num_hab    PLS_INTEGER;
    v_n          PLS_INTEGER;
    v_ini        PLS_INTEGER;
    v_idx        PLS_INTEGER;
    v_r          NUMBER;
    v_nombre     VARCHAR2(120);
    v_direccion  VARCHAR2(200);
    v_telefono   VARCHAR2(25);
    v_numero     VARCHAR2(20);
    v_estado     VARCHAR2(15);
    v_serv_nom   VARCHAR2(80);
    v_serv_prec  NUMBER;
    v_gratis     CHAR(1);
BEGIN
    FOR m IN 1 .. 12 LOOP
        FOR k IN 1 .. 5 LOOP
            v_id_aloj := v_id_aloj + 1;
            v_tipo    := MOD(m + k, 6) + 1;

            -- MOD(m*7 + k*3, 20) da 5 palabras distintas dentro del municipio,
            -- asi se respeta UNIQUE (id_municipio, nombre).
            v_nombre := v_prefijos(v_tipo) || ' '
                        || v_palabras(MOD(m * 7 + k * 3, 20) + 1);

            IF v_tipo IN (1, 3, 5) THEN
                v_direccion := 'Vereda ' || v_palabras(MOD(m + k * 5, 20) + 1)
                               || ' Km ' || TRUNC(DBMS_RANDOM.VALUE(1, 16));
            ELSE
                v_direccion := 'Calle ' || TRUNC(DBMS_RANDOM.VALUE(1, 40))
                               || ' # ' || TRUNC(DBMS_RANDOM.VALUE(1, 30))
                               || ' - ' || TRUNC(DBMS_RANDOM.VALUE(1, 99));
            END IF;

            v_telefono := '606' || TO_CHAR(TRUNC(DBMS_RANDOM.VALUE(7000000, 7999999)));

            INSERT INTO alojamiento (
                id_alojamiento, id_propietario, id_municipio,
                id_tipo_alojamiento, nombre, direccion, telefono, estado
            ) VALUES (
                v_id_aloj, MOD(v_id_aloj - 1, 30) + 1, m,
                v_tipo, v_nombre, v_direccion, v_telefono, 'ACTIVO'
            );

            -- Habitaciones (IDs consecutivos por alojamiento)
            v_num_hab := CASE WHEN v_id_aloj <= 40 THEN 7 ELSE 6 END;

            FOR j IN 1 .. v_num_hab LOOP
                v_id_hab := v_id_hab + 1;
                v_r := DBMS_RANDOM.VALUE;

                IF v_tipo = 4 THEN          -- Hostal
                    v_tipo_hab := CASE WHEN v_r < 0.3 THEN 1
                                       WHEN v_r < 0.6 THEN 2
                                       ELSE 6 END;
                ELSIF v_tipo = 3 THEN       -- Glamping
                    v_tipo_hab := CASE WHEN v_r < 0.6 THEN 2 ELSE 5 END;
                ELSE
                    v_tipo_hab := CASE WHEN v_r < 0.15 THEN 1
                                       WHEN v_r < 0.55 THEN 2
                                       WHEN v_r < 0.70 THEN 3
                                       WHEN v_r < 0.90 THEN 4
                                       ELSE 5 END;
                END IF;

                v_numero := TO_CHAR(100 * (TRUNC((j - 1) / 4) + 1) + MOD(j - 1, 4) + 1);

                -- Unas pocas habitaciones quedan en mantenimiento.
                v_estado := CASE WHEN MOD(v_id_hab, 67) = 0
                                 THEN 'MANTENIMIENTO' ELSE 'DISPONIBLE' END;

                INSERT INTO habitacion (
                    id_habitacion, id_alojamiento, id_tipo_habitacion,
                    numero_habitacion, estado
                ) VALUES (
                    v_id_hab, v_id_aloj, v_tipo_hab, v_numero, v_estado
                );
            END LOOP;

            -- Comodidades: entre 4 y 8 distintas por alojamiento
            v_n   := TRUNC(DBMS_RANDOM.VALUE(4, 9));
            v_ini := TRUNC(DBMS_RANDOM.VALUE(0, 14));
            FOR c IN 0 .. v_n - 1 LOOP
                v_gratis := CASE WHEN DBMS_RANDOM.VALUE < 0.8 THEN 'S' ELSE 'N' END;
                INSERT INTO alojamiento_comodidad (id_alojamiento, id_comodidad, es_gratuito)
                VALUES (v_id_aloj, MOD(v_ini + c, 14) + 1, v_gratis);
            END LOOP;

            -- Servicios: entre 4 y 6 distintos por alojamiento (IDs consecutivos)
            v_n   := TRUNC(DBMS_RANDOM.VALUE(4, 7));
            v_ini := TRUNC(DBMS_RANDOM.VALUE(0, 8));
            FOR s IN 0 .. v_n - 1 LOOP
                v_id_serv   := v_id_serv + 1;
                v_idx       := MOD(v_ini + s, 8) + 1;
                v_serv_nom  := v_serv_nombres(v_idx);
                v_serv_prec := ROUND(v_serv_precios(v_idx) * DBMS_RANDOM.VALUE(0.85, 1.2), -3);

                INSERT INTO servicio (id_servicio, id_alojamiento, nombre, precio_unitario, estado)
                VALUES (v_id_serv, v_id_aloj, v_serv_nom, v_serv_prec, 'ACTIVO');
            END LOOP;
        END LOOP;
    END LOOP;

    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Alojamientos: ' || v_id_aloj || ', habitaciones: ' || v_id_hab
                         || ', servicios: ' || v_id_serv);
END;

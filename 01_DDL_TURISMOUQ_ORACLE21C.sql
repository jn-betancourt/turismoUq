CREATE TABLE reserva (
    id_reserva       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    id_cliente       NUMBER       NOT NULL,
    id_alojamiento   NUMBER,
    fecha_reserva    TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    fecha_checkin    DATE         NOT NULL,
    fecha_checkout   DATE         NOT NULL,
    estado           VARCHAR2(12) DEFAULT 'PENDIENTE' NOT NULL,
    valor_total      NUMBER(12,2) DEFAULT 0 NOT NULL,

    CONSTRAINT pk_reserva PRIMARY KEY (id_reserva),
    CONSTRAINT ck_reserva_fechas CHECK (fecha_checkout > fecha_checkin),
    CONSTRAINT ck_reserva_estado
        CHECK (estado IN (
            'PENDIENTE', 'CONFIRMADA', 'CHECKED_IN',
            'FINALIZADA', 'CANCELADA'
        )),
    CONSTRAINT ck_reserva_valor_total CHECK (valor_total >= 0),
    CONSTRAINT fk_reserva_cliente
        FOREIGN KEY (id_cliente)
        REFERENCES cliente (id_usuario),
    CONSTRAINT fk_reserva_alojamiento
        FOREIGN KEY (id_alojamiento)
        REFERENCES alojamiento (id_alojamiento)
);

COMMENT ON TABLE reserva IS
    'Cabecera de la reserva; una reserva puede incluir varias habitaciones.';

CREATE TABLE reserva_habitacion (
    id_reserva                NUMBER       NOT NULL,
    id_habitacion             NUMBER       NOT NULL,

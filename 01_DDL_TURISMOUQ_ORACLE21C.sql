-- Oracle crea automaticamente indices para PRIMARY KEY y UNIQUE. Por eso aqui
-- solo se agregan indices de FK que no quedaron cubiertos por dichos indices.
-- Los indices de analitica se definiran en la Entrega 3 despues de medir planes.


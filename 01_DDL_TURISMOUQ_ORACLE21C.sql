    precio_estadia_habitacion NUMBER(12,2) NOT NULL,

    CONSTRAINT pk_reserva_habitacion
        PRIMARY KEY (id_reserva, id_habitacion),
    CONSTRAINT ck_reserva_hab_personas CHECK (personas_hospedadas > 0),
    CONSTRAINT ck_reserva_hab_precio CHECK (precio_estadia_habitacion >= 0),
    CONSTRAINT fk_reserva_hab_reserva

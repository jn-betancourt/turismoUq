CREATE TABLE usuario_sistema (
    id_usuario       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    username         VARCHAR2(30)  NOT NULL,
    password_hash    VARCHAR2(128) NOT NULL,
    nombre_completo  VARCHAR2(100) NOT NULL,
    email             VARCHAR2(100) NOT NULL,
    tipo_usuario      VARCHAR2(20)  NOT NULL,
    estado            VARCHAR2(10)  DEFAULT 'ACTIVO' NOT NULL,
    fecha_registro    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_usuario_sistema PRIMARY KEY (id_usuario),
    CONSTRAINT uq_usuario_username UNIQUE (username),
    CONSTRAINT uq_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_username
        CHECK (TRIM(username) IS NOT NULL),
    CONSTRAINT ck_usuario_nombre
        CHECK (TRIM(nombre_completo) IS NOT NULL),
    CONSTRAINT ck_usuario_email
        CHECK (email LIKE '%_@_%._%'),
    CONSTRAINT ck_usuario_tipo
        CHECK (tipo_usuario IN (
            'CLIENTE',
            'PROPIETARIO',
            'RECEPCION',
            'ADMIN_ALOJAMIENTO',
            'GERENTE',
            'AUDITOR'
        )),
    CONSTRAINT ck_usuario_estado
        CHECK (estado IN ('ACTIVO', 'INACTIVO', 'BLOQUEADO'))
);

COMMENT ON TABLE usuario_sistema IS
    'Supertipo de autenticacion centralizada para todos los usuarios.';
COMMENT ON COLUMN usuario_sistema.tipo_usuario IS
    'Discriminador de la especializacion de usuario.';
COMMENT ON COLUMN usuario_sistema.password_hash IS
    'Hash de la contrasena; nunca almacena la contrasena en texto plano.';

CREATE TABLE propietario (
    id_usuario              NUMBER       NOT NULL,

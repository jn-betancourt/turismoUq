COMMENT ON TABLE pago IS
    'Transacciones financieras asociadas a las reservas.';

CREATE TABLE reserva_servicio (
    id_reserva              NUMBER       NOT NULL,
    id_servicio             NUMBER       NOT NULL,
    cantidad                NUMBER(6)    NOT NULL,
    precio_unitario_aplicado NUMBER(10,2) NOT NULL,
    subtotal                NUMBER(12,2) NOT NULL,

    CONSTRAINT pk_reserva_servicio
        PRIMARY KEY (id_reserva, id_servicio),
    CONSTRAINT ck_reserva_serv_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_reserva_serv_precio CHECK (precio_unitario_aplicado >= 0),
    CONSTRAINT ck_reserva_serv_subtotal
        CHECK (subtotal = ROUND(cantidad * precio_unitario_aplicado, 2)),
    CONSTRAINT fk_reserva_serv_reserva
        FOREIGN KEY (id_reserva)
        REFERENCES reserva (id_reserva)
        ON DELETE CASCADE,
    CONSTRAINT fk_reserva_serv_servicio
        FOREIGN KEY (id_servicio)
        REFERENCES servicio (id_servicio)
);

COMMENT ON TABLE reserva_servicio IS
    'Servicios contratados; conserva el precio aplicado en la transaccion.';

CREATE TABLE resena (
    id_resena       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    id_reserva      NUMBER        NOT NULL,
    id_alojamiento  NUMBER        NOT NULL,
    calificacion    NUMBER(1)     NOT NULL,
    comentario      VARCHAR2(1000),
    fecha_resena    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_resena PRIMARY KEY (id_resena),
    CONSTRAINT uq_resena_reserva UNIQUE (id_reserva),
    CONSTRAINT ck_resena_calificacion CHECK (calificacion BETWEEN 1 AND 5),
    CONSTRAINT fk_resena_reserva
        FOREIGN KEY (id_reserva)
        REFERENCES reserva (id_reserva),
    CONSTRAINT fk_resena_alojamiento
        FOREIGN KEY (id_alojamiento)
        REFERENCES alojamiento (id_alojamiento)
);

COMMENT ON TABLE resena IS
    'Evaluacion de la estadia; se permite una sola resena por reserva.';

CREATE TABLE liquidacion_mensual (
    id_liquidacion      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    id_alojamiento      NUMBER       NOT NULL,
    periodo_anio        NUMBER(4)    NOT NULL,
    periodo_mes         NUMBER(2)    NOT NULL,
    total_hospedaje     NUMBER(14,2) DEFAULT 0 NOT NULL,
    total_servicios     NUMBER(14,2) DEFAULT 0 NOT NULL,
    comision_plataforma NUMBER(14,2) DEFAULT 0 NOT NULL,
    neto_propietario    NUMBER(14,2) DEFAULT 0 NOT NULL,
    fecha_liquidacion   DATE         DEFAULT SYSDATE NOT NULL,
    estado              VARCHAR2(10) DEFAULT 'CALCULADA' NOT NULL,

    CONSTRAINT pk_liquidacion_mensual PRIMARY KEY (id_liquidacion),
    CONSTRAINT uq_liquidacion_periodo
        UNIQUE (id_alojamiento, periodo_anio, periodo_mes),
    CONSTRAINT ck_liquidacion_anio CHECK (periodo_anio BETWEEN 2000 AND 9999),
    CONSTRAINT ck_liquidacion_mes CHECK (periodo_mes BETWEEN 1 AND 12),
    CONSTRAINT ck_liquidacion_montos
        CHECK (
            total_hospedaje >= 0
            AND total_servicios >= 0
            AND comision_plataforma >= 0
            AND neto_propietario >= 0
        ),
    CONSTRAINT ck_liquidacion_calculo
        CHECK (
            neto_propietario =
                ROUND(total_hospedaje + total_servicios - comision_plataforma, 2)
        ),
    CONSTRAINT ck_liquidacion_estado
        CHECK (estado IN ('CALCULADA', 'DISPERSADA', 'PAGADA')),
    CONSTRAINT fk_liquidacion_alojamiento
        FOREIGN KEY (id_alojamiento)
        REFERENCES alojamiento (id_alojamiento)
);

COMMENT ON TABLE liquidacion_mensual IS
    'Corte contable mensual por alojamiento para pago al propietario.';

-- Esta tabla y sus indices se ubican en el tablespace historico.
CREATE TABLE historico_reserva (
    id_reserva       NUMBER       NOT NULL,
    id_cliente       NUMBER       NOT NULL,
    id_alojamiento   NUMBER       NOT NULL,
    fecha_reserva    TIMESTAMP    NOT NULL,
    fecha_checkin    DATE         NOT NULL,
    fecha_checkout   DATE         NOT NULL,
    estado           VARCHAR2(20) NOT NULL,
    valor_total      NUMBER(12,2) NOT NULL,
    fecha_archivado  TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT pk_historico_reserva
        PRIMARY KEY (id_reserva)
        USING INDEX TABLESPACE ts_historico_reservas,
    CONSTRAINT ck_hist_reserva_fechas CHECK (fecha_checkout > fecha_checkin),
    CONSTRAINT ck_hist_reserva_estado
        CHECK (estado IN ('FINALIZADA', 'CANCELADA')),
    CONSTRAINT ck_hist_reserva_valor CHECK (valor_total >= 0),
    CONSTRAINT fk_hist_reserva_origen
        FOREIGN KEY (id_reserva)
        REFERENCES reserva (id_reserva)
)
TABLESPACE ts_historico_reservas;

COMMENT ON TABLE historico_reserva IS
    'Instantanea de reservas cerradas, separada fisicamente para el historico.';


    CONSTRAINT pk_propietario PRIMARY KEY (id_usuario),
    CONSTRAINT uq_propietario_documento UNIQUE (documento_identidad),
    CONSTRAINT ck_propietario_documento
        CHECK (TRIM(documento_identidad) IS NOT NULL),
    CONSTRAINT ck_propietario_telefono
        CHECK (TRIM(telefono_contacto) IS NOT NULL),
    CONSTRAINT fk_propietario_usuario
